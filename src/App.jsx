import { useState, useCallback, useEffect, useMemo } from 'react'
import CalendarPanel from './components/CalendarPanel'
import DocumentPanel from './components/DocumentPanel'
import DoPanel from './components/DoPanel'
import SyncStatus from './components/SyncStatus'
import { calendarTasks, featureDocItems } from './data/sampleData'
import {
  isGoogleConnected,
  connectGoogleCalendar,
  disconnectGoogleCalendar,
  fetchGoogleEvents,
  mapGoogleEventsByDate,
  createGoogleEvent,
} from './services/googleCalendar'
import { isUnlocked, getState, putState } from './services/api'
import './App.css'

const CALENDAR_STORAGE_KEY = 'innernet:calendar-state:v1'

function loadCalendarState() {
  try {
    const raw = localStorage.getItem(CALENDAR_STORAGE_KEY)
    if (raw) return JSON.parse(raw)
  } catch {}
  return { userEvents: {}, eventOverrides: {}, thoughts: {} }
}

function getTodayStr() {
  const now = new Date()
  const y = now.getFullYear()
  const m = String(now.getMonth() + 1).padStart(2, '0')
  const d = String(now.getDate()).padStart(2, '0')
  return `${y}-${m}-${d}`
}

function App() {
  const [selectedDate, setSelectedDate] = useState(getTodayStr())
  const [selectedEvent, setSelectedEvent] = useState(null)
  const [sidebarWidth, setSidebarWidth] = useState(340)
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false)
  const initialCalendarState = useState(loadCalendarState)[0]
  const [thoughts, setThoughts] = useState(initialCalendarState.thoughts)
  const [quickSlot, setQuickSlot] = useState(null)
  // User-created events from the natural-language scheduler — keyed by date
  // string, same shape as calendarTasks. Merged with static data in the panel.
  const [userEvents, setUserEvents] = useState(initialCalendarState.userEvents)
  // Overrides from drag-to-reschedule / resize — { [eventId]: { time, endTime } }
  const [eventOverrides, setEventOverrides] = useState(initialCalendarState.eventOverrides)

  // ── Persistence: localStorage always (fast, same-browser), Worker/KV when
  // the sync secret is unlocked (cross-device, source of truth once synced).
  const [apiUnlocked, setApiUnlocked] = useState(isUnlocked())
  const [apiSyncing, setApiSyncing] = useState(false)
  const [calendarSynced, setCalendarSynced] = useState(false)

  useEffect(() => {
    try {
      localStorage.setItem(CALENDAR_STORAGE_KEY, JSON.stringify({ userEvents, eventOverrides, thoughts }))
    } catch {}
  }, [userEvents, eventOverrides, thoughts])

  const pullCalendarFromApi = useCallback(async () => {
    setApiSyncing(true)
    try {
      const remote = await getState('calendar')
      if (remote) {
        if (remote.userEvents) setUserEvents(remote.userEvents)
        if (remote.eventOverrides) setEventOverrides(remote.eventOverrides)
        if (remote.thoughts) setThoughts(remote.thoughts)
      }
    } catch {
      // Locked, offline, or server error — local state stands as-is.
    } finally {
      setCalendarSynced(true)
      setApiSyncing(false)
    }
  }, [])

  useEffect(() => {
    if (apiUnlocked) pullCalendarFromApi()
  }, [apiUnlocked, pullCalendarFromApi])

  // Push to the Worker (debounced) once the initial pull has landed, so a
  // local-only edit made before unlocking doesn't get silently clobbered.
  useEffect(() => {
    if (!apiUnlocked || !calendarSynced) return
    const t = setTimeout(() => {
      putState('calendar', { userEvents, eventOverrides, thoughts }).catch(() => {})
    }, 800)
    return () => clearTimeout(t)
  }, [apiUnlocked, calendarSynced, userEvents, eventOverrides, thoughts])

  // Google Calendar sync — events fetched from the user's real calendar,
  // kept separate from userEvents so a re-sync can cleanly replace them.
  const [googleEvents, setGoogleEvents] = useState({})
  const [googleConnected, setGoogleConnected] = useState(false)
  const [googleSyncing, setGoogleSyncing] = useState(false)
  const [googleError, setGoogleError] = useState(null)

  // Bottom panel state
  const [bottomCollapsed, setBottomCollapsed] = useState(false)
  const [bottomHeight, setBottomHeight] = useState(280)

  // Agent feature windows (spawned by "Implement All" or "Ask AI")
  const [featureWindows, setFeatureWindows] = useState([])
  const [activeAgentFeatures, setActiveAgentFeatures] = useState([])

  // Extra logs generated by actions
  const [extraLogs, setExtraLogs] = useState([])

  // Auto-select first event of the day
  useEffect(() => {
    const dayEvents = [...(calendarTasks[selectedDate] || []), ...(userEvents[selectedDate] || []), ...(googleEvents[selectedDate] || [])]
    if (dayEvents.length > 0) {
      setSelectedEvent(dayEvents[0])
    } else {
      setSelectedEvent(null)
    }
    setQuickSlot(null)
  }, [selectedDate])

  // ── Google Calendar ──
  useEffect(() => {
    setGoogleConnected(isGoogleConnected())
  }, [])

  const syncGoogleEvents = useCallback(async () => {
    setGoogleSyncing(true)
    setGoogleError(null)
    try {
      const now = new Date()
      const timeMin = new Date(now); timeMin.setDate(timeMin.getDate() - 30)
      const timeMax = new Date(now); timeMax.setDate(timeMax.getDate() + 90)
      const items = await fetchGoogleEvents(timeMin.toISOString(), timeMax.toISOString())
      setGoogleEvents(mapGoogleEventsByDate(items))
      setGoogleConnected(true)
    } catch (err) {
      setGoogleError(err.message)
    } finally {
      setGoogleSyncing(false)
    }
  }, [])

  // Called when the search box parses a "schedule …" intent. Only appends the
  // event to userEvents — intentionally does NOT navigate away from the
  // current date so the user sees the success confirmation first and jumps
  // explicitly via the confirmation card.
  const handleScheduleEvent = useCallback((date, event) => {
    setUserEvents(prev => ({
      ...prev,
      [date]: [...(prev[date] || []), event],
    }))
    if (googleConnected) {
      createGoogleEvent(date, event)
        .then(() => {
          // It now exists on Google too — drop the local optimistic copy
          // and re-sync so the confirmed Google-sourced version takes over
          // instead of both sitting in state under different ids.
          setUserEvents(prev => ({
            ...prev,
            [date]: (prev[date] || []).filter(e => e.id !== event.id),
          }))
          syncGoogleEvents()
        })
        .catch(err => setGoogleError(err.message))
    }
  }, [googleConnected, syncGoogleEvents])

  const handleGoogleConnect = useCallback(async () => {
    if (googleConnected) {
      disconnectGoogleCalendar()
      setGoogleConnected(false)
      setGoogleEvents({})
      return
    }
    try {
      await connectGoogleCalendar()
      setGoogleConnected(true)
    } catch (err) {
      setGoogleError(err.message)
    }
  }, [googleConnected])

  // Keep synced with edits/deletes made directly in Google Calendar: sync
  // immediately on connect, then on an interval and whenever the tab regains
  // focus (there's no backend for push/webhook updates, so polling is it).
  useEffect(() => {
    if (!googleConnected) return
    syncGoogleEvents()
    const interval = setInterval(syncGoogleEvents, 2 * 60 * 1000)
    const onFocus = () => syncGoogleEvents()
    window.addEventListener('focus', onFocus)
    return () => {
      clearInterval(interval)
      window.removeEventListener('focus', onFocus)
    }
  }, [googleConnected, syncGoogleEvents])

  // Merge live Google events on top of app-native userEvents for rendering.
  // A locally-created event that was also pushed to Google (see
  // handleScheduleEvent) can briefly — or, for events created before this
  // dedup existed, indefinitely — exist in both userEvents and googleEvents
  // under different ids. Drop the local copy whenever a Google-sourced event
  // matches it on date/time/title so it doesn't render twice.
  const mergedUserEvents = useMemo(() => {
    const merged = {}
    const allDates = new Set([...Object.keys(userEvents), ...Object.keys(googleEvents)])
    allDates.forEach(date => {
      const own = userEvents[date] || []
      const google = googleEvents[date] || []
      const dedupedOwn = own.filter(ev =>
        !google.some(g => g.time === ev.time && g.endTime === ev.endTime && g.title === ev.title)
      )
      merged[date] = [...dedupedOwn, ...google]
    })
    return merged
  }, [userEvents, googleEvents])

  // Called when an event is dragged or resized to update its time/endTime
  const handleEventUpdate = useCallback((eventId, date, newTime, newEndTime) => {
    setEventOverrides(prev => ({
      ...prev,
      [eventId]: { time: newTime, endTime: newEndTime },
    }))
  }, [])

  const handleSlotClick = useCallback((time, label) => {
    setSelectedEvent(null)
    setQuickSlot({ time, label })
  }, [])

  const clearQuickSlot = useCallback(() => {
    setQuickSlot(null)
  }, [])

  // Called when user types a note in the inline quick-slot input and hits Enter.
  // Writes into `thoughts` under slot-${date}-${time}; the calendar re-renders
  // the thought as a persistent purple thought-block at that time.
  const handleQuickNoteAdd = useCallback((time, text) => {
    const clean = (text || '').trim()
    if (!clean) return
    const key = `slot-${selectedDate}-${time}`
    const now = new Date()
    const timeLabel = now.toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit', hour12: true })
    setThoughts(prev => ({
      ...prev,
      [key]: [...(prev[key] || []), { text: clean, time: timeLabel, id: Date.now() }],
    }))
  }, [selectedDate])

  const handleThoughtDelete = useCallback((time, id) => {
    const key = `slot-${selectedDate}-${time}`
    setThoughts(prev => {
      const items = (prev[key] || []).filter(it => it.id !== id)
      const next = { ...prev }
      if (items.length === 0) delete next[key]
      else next[key] = items
      return next
    })
  }, [selectedDate])

  const handleThoughtUpdate = useCallback((time, id, newText) => {
    const clean = (newText || '').trim()
    if (!clean) return
    const key = `slot-${selectedDate}-${time}`
    setThoughts(prev => ({
      ...prev,
      [key]: (prev[key] || []).map(it => it.id === id ? { ...it, text: clean } : it),
    }))
  }, [selectedDate])

  // Ask AI on a feature
  const handleAskAI = useCallback((featId, title, context) => {
    const newWindow = { id: featId, title, context }
    setFeatureWindows(prev => {
      if (prev.some(w => w.id === featId)) return prev
      return [...prev, newWindow]
    })
    setActiveAgentFeatures(prev => prev.includes(featId) ? prev : [...prev, featId])
    setExtraLogs(prev => [...prev, {
      id: `dyn-${Date.now()}`,
      time: new Date().toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false }),
      type: 'user',
      action: `Clicked "Ask AI" on "${title}"`,
      session: featId,
    }])
  }, [])

  // Implement All
  const handleImplementAll = useCallback(() => {
    const windows = featureDocItems.map(f => ({
      id: f.id,
      title: f.title,
      context: f.bullets.map(b => typeof b === 'string' ? b : b.text).join('\n'),
    }))
    setFeatureWindows(windows)
    setActiveAgentFeatures(windows.map(w => w.id))
    setExtraLogs(prev => [...prev, {
      id: `dyn-${Date.now()}`,
      time: new Date().toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false }),
      type: 'system',
      action: `"Implement All" triggered — ${windows.length} agent sessions spawned`,
      session: null,
    }])
  }, [])

  // Resize handlers
  const handleBottomResizeStart = useCallback((e) => {
    e.preventDefault()
    const startY = e.clientY
    const startHeight = bottomHeight
    const onMouseMove = (moveEvent) => {
      const delta = startY - moveEvent.clientY
      setBottomHeight(Math.min(Math.max(startHeight + delta, 150), 600))
    }
    const onMouseUp = () => {
      document.removeEventListener('mousemove', onMouseMove)
      document.removeEventListener('mouseup', onMouseUp)
      document.body.style.cursor = ''
      document.body.style.userSelect = ''
    }
    document.body.style.cursor = 'ns-resize'
    document.body.style.userSelect = 'none'
    document.addEventListener('mousemove', onMouseMove)
    document.addEventListener('mouseup', onMouseUp)
  }, [bottomHeight])

  const handleSidebarResizeStart = useCallback((e) => {
    e.preventDefault()
    const startX = e.clientX
    const startWidth = sidebarWidth
    const onMouseMove = (moveEvent) => {
      const delta = moveEvent.clientX - startX
      setSidebarWidth(Math.min(Math.max(startWidth + delta, 260), 500))
    }
    const onMouseUp = () => {
      document.removeEventListener('mousemove', onMouseMove)
      document.removeEventListener('mouseup', onMouseUp)
      document.body.style.cursor = ''
      document.body.style.userSelect = ''
    }
    document.body.style.cursor = 'ew-resize'
    document.body.style.userSelect = 'none'
    document.addEventListener('mousemove', onMouseMove)
    document.addEventListener('mouseup', onMouseUp)
  }, [sidebarWidth])


  return (
    <div className="app">
      <SyncStatus
        unlocked={apiUnlocked}
        syncing={apiSyncing}
        onUnlock={() => {
          setApiUnlocked(true)
          window.dispatchEvent(new Event('innernet:unlocked'))
        }}
      />
      {/* Left: Calendar sidebar */}
      {!sidebarCollapsed && (
        <aside className="app-sidebar-calendar" style={{ width: `${sidebarWidth}px` }}>
          <CalendarPanel
            selectedDate={selectedDate}
            setSelectedDate={setSelectedDate}
            selectedEvent={selectedEvent}
            setSelectedEvent={(ev) => { setSelectedEvent(ev); setQuickSlot(null) }}
            onSlotClick={handleSlotClick}
            onQuickNoteAdd={handleQuickNoteAdd}
            onThoughtDelete={handleThoughtDelete}
            onThoughtUpdate={handleThoughtUpdate}
            onQuickSlotClear={clearQuickSlot}
            quickSlot={quickSlot}
            thoughts={thoughts}
            userEvents={mergedUserEvents}
            onScheduleEvent={handleScheduleEvent}
            onEventUpdate={handleEventUpdate}
            eventOverrides={eventOverrides}
            googleConnected={googleConnected}
            googleSyncing={googleSyncing}
            googleError={googleError}
            onGoogleConnect={handleGoogleConnect}
            onGoogleRefresh={syncGoogleEvents}
          />
        </aside>
      )}

      {/* Sidebar toggle + resize handle */}
      <div className={`sidebar-divider ${sidebarCollapsed ? 'collapsed' : ''}`}>
        {!sidebarCollapsed && (
          <div className="sidebar-resize-zone" onMouseDown={handleSidebarResizeStart} />
        )}
        <button
          className="sidebar-toggle-btn"
          onClick={() => setSidebarCollapsed(prev => !prev)}
          title={sidebarCollapsed ? 'Show Calendar' : 'Hide Calendar'}
        >
          <svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round">
            {sidebarCollapsed
              ? <polyline points="9 18 15 12 9 6" />
              : <polyline points="15 18 9 12 15 6" />
            }
          </svg>
          {sidebarCollapsed && <span>Plan</span>}
        </button>
        {!sidebarCollapsed && (
          <div className="sidebar-resize-zone" onMouseDown={handleSidebarResizeStart} />
        )}
      </div>

      {/* Right: Main area — shows either Do (chat) or Think (docs), never both */}
      <div className="app-main">
        {/* Do area: Chat Windows — visible when bottomCollapsed (i.e. Think is hidden) */}
        {bottomCollapsed && (
          <div className="app-top" style={{ flex: 1 }}>
            <DoPanel />
          </div>
        )}

        {/* Toggle between Do and Think */}
        <div className="bottom-divider">
          <button
            className="bottom-toggle-btn"
            onClick={() => setBottomCollapsed(prev => !prev)}
            title={bottomCollapsed ? 'Switch to Think' : 'Switch to Do'}
          >
            <svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round">
              {bottomCollapsed
                ? <polyline points="18 15 12 9 6 15" />
                : <polyline points="6 9 12 15 18 9" />
              }
            </svg>
            <span>{bottomCollapsed ? 'Think' : 'Do'}</span>
          </button>
        </div>

        {/* Think area: Document + Logs — visible when NOT bottomCollapsed */}
        {!bottomCollapsed && (
          <div className="app-bottom" style={{ flex: 1 }}>
            <div className="bottom-split" style={{ flex: 1 }}>
              <DocumentPanel
                selectedDate={selectedDate}
                onAskAI={handleAskAI}
                activeAgentFeatures={activeAgentFeatures}
              />
            </div>
          </div>
        )}

      </div>
    </div>
  )
}

export default App
